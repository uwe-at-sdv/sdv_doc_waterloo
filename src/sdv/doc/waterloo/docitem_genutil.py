def parse_source_fragment(profile: Profile, source_fragment: str) -> ast.AST | None:
	r"""
	Preamble:
		profile:
			function
		normative_sections:
			Contract, Parameters, Returns, Raises
		scope:
			extension
	Contract:
		general:
			|Must| return |None| if |var|`profile` is |value|`module`.
			|Must| parse |var|`source_fragment` via |mod|`ast`.
			|Must| return the first top-level AST node from the parsed tree.
			|Must| ensure the returned node matches |var|`profile`:
			For |value|`class`, the node |must| be |type|`ast.ClassDef`.
			For |value|`function`, |value|`method`, or |value|`inherited_method`, the node |must| be |type|`ast.FunctionDef` or |type|`ast.AsyncFunctionDef`.
			|Must| reject empty parses (no top-level nodes).

	Parameters:
		profile:
			Profile used for node-type validation.
		source_fragment:
			Source fragment containing a class/function/method header (or small stub).
			Ignored if |var|`profile` is |value|`module`.
	Returns:
		|None| for profile |value|`module`, otherwise the validated first AST node.
	Raises:
		SyntaxError:
			|May| be raised by |func|`ast.parse` for invalid Python syntax.
		RuntimeError:
			|Must| raise if no top-level node exists after parsing.
			|Must| raise if the parsed node type does not match |var|`profile`.
	"""
	if profile == "module":
		return None
	tree = ast.parse(source_fragment)
	if not tree.body:
		raise RuntimeError("source_fragment is empty after parsing")
	node: ast.AST = tree.body[0]
	if profile == "class" and not isinstance(node, ast.ClassDef):
		raise RuntimeError("source_fragment does not parse to a class header")
	if profile in {"function", "method", "inherited_method"} and not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
		raise RuntimeError("source_fragment does not parse to a function/method header")
	return node


def parse_signature_fragment(profile: Profile, signature: str) -> ast.AST | None:
	r"""
	Preamble:
		profile:
			function
		normative_sections:
			Contract, Parameters, Returns, Raises
		scope:
			extension
	Contract:
		general:
			|Must| turn a textual signature fragment into a small synthetic source fragment that can be parsed by |func|`parse_source_fragment`.
			|Must| return |None| for profile |value|`module`.
			|Must| accept signatures with or without leading |lit|`class`, |lit|`def`, or |lit|`async def` keywords.
			|Must| synthesize a minimal valid body so that the resulting fragment can be parsed by |mod|`ast`.
			|Must| keep the produced fragment close to the AST shape consumed by the existing template generators.
		requires:
			|Must| provide a non-empty signature for non-|value|`module` profiles.
	Parameters:
		profile:
			Waterloo docstring profile to target.
		signature:
			Textual signature fragment.
	Returns:
		|None| for profile |value|`module`, otherwise the parsed AST node of the synthetic fragment.
	Raises:
		RuntimeError:
			|Must| raise if the signature is empty or the synthetic fragment cannot be parsed.
	Notes:
		Bridge:
			This helper exists so that MCP and IDE callers can feed a textual signature
			through the same AST-based docstring generation pipeline that is used by the
			canonical template generator script.
	"""
	if profile == "module":
		return None
	signature = signature.strip()
	if not signature:
		raise RuntimeError("signature is empty")
	normalized = signature.rstrip().rstrip(":")
	if profile == "class":
		if normalized.startswith("class "):
			normalized = normalized[len("class ") :].lstrip()
		source_fragment = f"class {normalized}:\n\tpass"
		return parse_source_fragment(profile, source_fragment)
	if normalized.startswith("async def "):
		body = f"{normalized}:\n\tpass"
	elif normalized.startswith("def "):
		body = f"{normalized}:\n\tpass"
	else:
		body = f"def {normalized}:\n\tpass"
	return parse_source_fragment(profile, body)

def infer_docstring_profile(obj: object) -> Profile:
	r"""
	Preamble:
		profile:
			function
		normative_sections:
			Contract, Parameters, Returns, Raises
		scope:
			extension
	Contract:
		general:
			|Must| derive the best matching waterloo docstring profile from the object.
	Parameters:
		obj:
			Object to inspect.
	Returns:
	Raises:
		RuntimeError:
			|Must| raise if |var|`obj` does not match any of the categories |lit|`module`, |lit|`class`, |lit|`callable`.
	Notes:
		Result:
			The |value|`inherited_method` profile is never returned because it
			does not differ from the |value|`method` profile based solely on formal criteria.
			
	"""
	if is_obj_module(obj):
		return "module"
	if is_obj_class(obj):
		return "class"
	if is_obj_method_like(obj):
		return "method"
	if is_obj_function(obj):
		return "function"
	raise RuntimeError(f"cannot infer docstring profile for object type {type(obj).__name__}")


def _parameter_names_from_callable(
	obj: object,
	*,
	drop_first_receiver: bool = False,
) -> list[str]:
	try:
		sig = inspect.signature(cast_callable(obj))
	except Exception:
		return []
	names: list[str] = []
	for p in sig.parameters.values():
		names.append(str(p.name))
	if drop_first_receiver and names:
		first = names[0]
		if first in {"self", "cls", "mcls"}:
			names = names[1:]
	return names


def _parameter_names_from_function_node(
	node: ast.FunctionDef | ast.AsyncFunctionDef,
	*,
	drop_first_receiver: bool = False,
) -> list[str]:
	names: list[str] = []
	for arg in node.args.posonlyargs:
		names.append(arg.arg)
	for arg in node.args.args:
		names.append(arg.arg)
	if drop_first_receiver and names:
		first = names[0]
		if first in {"self", "cls", "mcls"}:
			names = names[1:]
	for arg in node.args.kwonlyargs:
		names.append(arg.arg)
	return names


def cast_callable(obj: object) -> Callable[..., Any]:
	return obj if callable(obj) else _raise_not_callable(obj)


def _raise_not_callable(obj: object) -> Callable[..., Any]:
	raise RuntimeError(f"object is not callable: {type(obj).__name__}")


def _full_returns_line(obj: object) -> str:
	try:
		sig = inspect.signature(cast_callable(obj))
	except Exception:
		return "\t|Must| return ..."
	ann = sig.return_annotation
	if ann is inspect.Signature.empty:
		return "\t|Must| return ..."
	if ann is None:
		return "\t|Must| return |None|."
	if ann is bool:
		return "\t|Must| return |True| if ... and |False| otherwise."
	if ann is str:
		return "\t|Must| return ..."
	ann_str = str(ann)
	if ann_str in {"None", "NoneType"}:
		return "\t|Must| return |None|."
	if ann_str == "Self" or "typing.Self" in ann_str:
		return "\t|Must| return |Self| for fluent-style chaining."
	if ann_str == "<class 'bool'>":
		return "\t|Must| return |True| if ... and |False| otherwise."
	return "\t|Must| return ..."


def _full_returns_line_from_node(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
	ann = node.returns
	if ann is None:
		return "\t|Must| return ..."
	if isinstance(ann, ast.Constant) and ann.value is None:
		return "\t|Must| return |None|."
	if isinstance(ann, ast.Name):
		if ann.id == "None":
			return "\t|Must| return |None|."
		if ann.id == "Self":
			return "\t|Must| return |Self| for fluent-style chaining."
		if ann.id == "bool":
			return "\t|Must| return |True| if ... and |False| otherwise."
	return "\t|Must| return ..."


