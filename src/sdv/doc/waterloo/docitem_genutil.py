r"""
Preamble:
	profile:
		module
	normative_sections:
		Contract, Public_functions
	scope:
		extension
Contract:
	general:
		|Must| provide functions for generating minimal and full waterloo docstring templates.
		|Must| represent the Single Source of Truth for the structure and content of these templates.
		|Should| represent the Single Source of Truth for future cuts of such templates.
		|Must| provide JSON representations of these templates as a result from a canonical generation process (e.g. a script) in order to avoid drift.
Description:
	This module is intended for IDE-extension workflows.
	A typical use case is a VSCode context-menu action on a |lit|`class` or |lit|`def` line:
	parse the selected header fragment, infer/select a profile, and generate a minimal or full Waterloo docstring template.
	The signature-to-AST bridge in |func|`parse_signature_fragment` is shared by MCP
	and IDE workflows. Keep it close to the AST-based generators so that the
	template text and any future JSON snippets continue to derive from the same
	canonical structure.
Public_functions:
	parse_source_fragment, infer_docstring_profile,
	parse_signature_fragment,
	generate_minimal_docstring, generate_full_docstring,
	generate_minimal_docstring_from_node, generate_full_docstring_from_node
Notes:
	Important:
		JSON templates for minimal and full docstring templates
		can be generated by means of |file|`$MAIN/tools/make_docstring_templates_json.sh`.
		This script should be used in order to avoid drift. It represents the canonical generation process
		for these templates, and the resulting JSON files are the Single Source of Truth for their structure and content.
		Any future JSON snippets produced from signature fragments should stay aligned with
		the same canonical structure in |path|`package_main/templates-json/out`.
"""

